// Формы фото-рамок. Сердце — CSS clip-path: polygon() в процентах блока:
// в PDF это векторный контур (CSS-маска печаталась бы растром, с волоском по
// краю рамки), а фото остаётся JPEG без пересжатия. Контур — то же сердце
// 100×92, под которое нарисованы окна рамок «Кружевное сердце» и «Игральная
// карта» (tools/stickers/generate.py): кривые Безье, разбитые на мелкие отрезки.

// Сердце в квадрате 100×92: (начало, контрольная 1, контрольная 2, конец) для каждого из 4 сегментов.
const HEART: [number, number][][] = [
  [[50, 90], [22, 70], [2, 52], [2, 28]],
  [[2, 28], [2, 12], [14, 2], [28, 2]],
  [[28, 2], [38, 2], [46, 8], [50, 17]],
  [[50, 17], [54, 8], [62, 2], [72, 2]],
  [[72, 2], [86, 2], [98, 12], [98, 28]],
  [[98, 28], [98, 52], [78, 70], [50, 90]],
]

function bezier([p0, p1, p2, p3]: [number, number][], t: number): [number, number] {
  const u = 1 - t
  const k = [u * u * u, 3 * u * u * t, 3 * u * t * t, t * t * t]
  return [0, 1].map((i) => k[0] * p0[i] + k[1] * p1[i] + k[2] * p2[i] + k[3] * p3[i]) as [number, number]
}

// Рисунок 100×92 растягивается на весь блок (как маска раньше): x/100, y/92.
const STEPS = 24
const points = HEART.flatMap((seg) => Array.from({ length: STEPS }, (_, i) => bezier(seg, i / STEPS)))
export const HEART_CLIP = `polygon(${points.map(([x, y]) => `${(x).toFixed(2)}% ${((y / 92) * 100).toFixed(2)}%`).join(', ')})`
